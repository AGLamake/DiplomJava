-- Информационная система мониторинга охраны недвижимости и автомобилей
-- СУБД: PostgreSQL 14+
-- Скрипт создаёт схему таблиц; интеграция с реальными датчиками/GPS требует отдельного адаптера.


CREATE TABLE roles (
    role_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(40) NOT NULL UNIQUE,
    description   TEXT
);

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       BIGINT NOT NULL REFERENCES roles(role_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    login         VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(160) NOT NULL,
    phone         VARCHAR(30),
    email         VARCHAR(254),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE clients (
    client_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_type    VARCHAR(20) NOT NULL CHECK (client_type IN ('individual','legal_entity')),
    name           VARCHAR(200) NOT NULL,
    contact_person VARCHAR(160),
    phone          VARCHAR(30) NOT NULL,
    email          VARCHAR(254),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(name)) > 0)
);

CREATE TABLE protected_objects (
    object_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT NOT NULL REFERENCES clients(client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    object_type     VARCHAR(20) NOT NULL CHECK (object_type IN ('real_estate','vehicle')),
    name            VARCHAR(160) NOT NULL,
    address         TEXT,
    object_status   VARCHAR(20) NOT NULL DEFAULT 'active'
                    CHECK (object_status IN ('active','suspended','closed')),
    security_status VARCHAR(20) NOT NULL DEFAULT 'disarmed'
                    CHECK (security_status IN ('armed','disarmed','alarm','unknown')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (object_type <> 'real_estate' OR address IS NOT NULL)
);

CREATE TABLE vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id  BIGINT NOT NULL UNIQUE REFERENCES protected_objects(object_id) ON UPDATE CASCADE ON DELETE CASCADE,
    brand      VARCHAR(80) NOT NULL,
    model      VARCHAR(80) NOT NULL,
    reg_number VARCHAR(20) NOT NULL UNIQUE,
    vin        VARCHAR(32) UNIQUE,
    CHECK (length(trim(reg_number)) > 0)
);

CREATE TABLE contracts (
    contract_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT NOT NULL REFERENCES clients(client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    contract_number VARCHAR(60) NOT NULL UNIQUE,
    signed_on       DATE NOT NULL,
    valid_from      DATE NOT NULL,
    valid_to        DATE,
    status          VARCHAR(20) NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft','active','expired','terminated')),
    price           NUMERIC(12,2) CHECK (price IS NULL OR price >= 0),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- Связь M:N: договор может включать несколько объектов; объект может участвовать в разных договорах во времени.
CREATE TABLE contract_objects (
    contract_id BIGINT NOT NULL REFERENCES contracts(contract_id) ON UPDATE CASCADE ON DELETE CASCADE,
    object_id   BIGINT NOT NULL REFERENCES protected_objects(object_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    PRIMARY KEY (contract_id, object_id)
);

CREATE TABLE equipment_types (
    equipment_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL UNIQUE,
    category          VARCHAR(40) NOT NULL CHECK (category IN ('controller','motion_sensor','opening_sensor','panic_button','water_sensor','fire_sensor','glass_sensor','gas_sensor','gps_tracker','other')),
    description       TEXT
);

CREATE TABLE equipment (
    equipment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id         BIGINT NOT NULL REFERENCES protected_objects(object_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    equipment_type_id BIGINT NOT NULL REFERENCES equipment_types(equipment_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    serial_number     VARCHAR(100) UNIQUE,
    installation_date DATE,
    status            VARCHAR(20) NOT NULL DEFAULT 'installed'
                      CHECK (status IN ('planned','installed','fault','removed'))
);

CREATE TABLE installation_requests (
    request_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id    BIGINT NOT NULL REFERENCES protected_objects(object_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_by   BIGINT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assigned_to  BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    scheduled_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    status       VARCHAR(20) NOT NULL DEFAULT 'new'
                 CHECK (status IN ('new','assigned','in_progress','completed','cancelled')),
    description  TEXT,
    CHECK (completed_at IS NULL OR scheduled_at IS NULL OR completed_at >= scheduled_at)
);

CREATE TABLE response_teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL UNIQUE,
    phone   VARCHAR(30),
    status  VARCHAR(20) NOT NULL DEFAULT 'available'
            CHECK (status IN ('available','dispatched','unavailable'))
);

CREATE TABLE team_members (
    team_id     BIGINT NOT NULL REFERENCES response_teams(team_id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    member_role VARCHAR(60),
    PRIMARY KEY (team_id, user_id)
);

CREATE TABLE alarm_events (
    event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id   BIGINT NOT NULL REFERENCES protected_objects(object_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    equipment_id BIGINT REFERENCES equipment(equipment_id) ON UPDATE CASCADE ON DELETE SET NULL,
    operator_id BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    event_type  VARCHAR(60) NOT NULL,
    priority    VARCHAR(15) NOT NULL DEFAULT 'medium'
                CHECK (priority IN ('low','medium','high','critical')),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status      VARCHAR(20) NOT NULL DEFAULT 'new'
                CHECK (status IN ('new','checking','confirmed','false_alarm','dispatching','closed')),
    latitude    NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude   NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    description TEXT
);

CREATE TABLE dispatches (
    dispatch_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT NOT NULL UNIQUE REFERENCES alarm_events(event_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    team_id      BIGINT NOT NULL REFERENCES response_teams(team_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    operator_id  BIGINT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    dispatched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    arrived_at   TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    result       VARCHAR(30) CHECK (result IS NULL OR result IN ('confirmed','false_alarm','no_access','other')),
    notes        TEXT,
    CHECK (arrived_at IS NULL OR arrived_at >= dispatched_at),
    CHECK (completed_at IS NULL OR arrived_at IS NULL OR completed_at >= arrived_at)
);

CREATE TABLE vehicle_locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id  BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON UPDATE CASCADE ON DELETE CASCADE,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    latitude    NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude   NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    speed       NUMERIC(7,2) CHECK (speed IS NULL OR speed >= 0)
);

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT NOT NULL REFERENCES clients(client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    event_id        BIGINT REFERENCES alarm_events(event_id) ON UPDATE CASCADE ON DELETE SET NULL,
    channel         VARCHAR(20) NOT NULL CHECK (channel IN ('in_app','sms','email','push')),
    message         TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at         TIMESTAMPTZ,
    status          VARCHAR(20) NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','sent','failed','read'))
);

CREATE TABLE audit_log (
    audit_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    action      VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id   BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details     JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX ix_objects_client ON protected_objects(client_id);
CREATE INDEX ix_contracts_client ON contracts(client_id);
CREATE INDEX ix_contract_objects_object ON contract_objects(object_id);
CREATE INDEX ix_equipment_object ON equipment(object_id);
CREATE INDEX ix_install_requests_status ON installation_requests(status, created_at DESC);
CREATE INDEX ix_alarm_events_object_time ON alarm_events(object_id, received_at DESC);
CREATE INDEX ix_alarm_events_status_time ON alarm_events(status, received_at DESC);
CREATE INDEX ix_dispatches_team_time ON dispatches(team_id, dispatched_at DESC);
CREATE INDEX ix_vehicle_locations_vehicle_time ON vehicle_locations(vehicle_id, recorded_at DESC);
CREATE INDEX ix_notifications_client_time ON notifications(client_id, created_at DESC);
CREATE INDEX ix_audit_log_entity_time ON audit_log(entity_type, entity_id, created_at DESC);

